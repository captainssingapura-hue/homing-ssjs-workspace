package hue.captains.singapura.js.homing.workspace.bench;

import hue.captains.singapura.js.homing.core.DomModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.workspace.widgets.WorkspaceManifest;

import java.util.List;

/**
 * The bench's workspace of one pane, as its page has it: {@code BENCH_WORKSPACE},
 * generated from {@link BenchWorkspace} - its kinds, each its class, its title
 * and the types its declaration says it joins; its root parties, each its type
 * and the secretary at its root - so the page's workspace is Java's, and no
 * second list can drift from it. A DOM module, though it touches no DOM: it
 * imports the widgets' classes (the Keyboard's §15 hazard).
 */
public record BenchWorkspaceModule() implements DomModule<BenchWorkspaceModule>, SelfContent {

    public static final BenchWorkspaceModule INSTANCE = new BenchWorkspaceModule();

    public record BENCH_WORKSPACE() implements Exportable._Constant<BenchWorkspaceModule> {}

    @Override public ImportsFor<BenchWorkspaceModule> imports() { return WorkspaceManifest.imports(BenchWorkspace.INSTANCE); }

    @Override
    public ExportsOf<BenchWorkspaceModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new BENCH_WORKSPACE())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by BenchWorkspaceModule from BenchWorkspace - do not hand-edit: its kinds, and its root parties.",
                       WorkspaceManifest.js("BENCH_WORKSPACE", BenchWorkspace.INSTANCE));
    }
}

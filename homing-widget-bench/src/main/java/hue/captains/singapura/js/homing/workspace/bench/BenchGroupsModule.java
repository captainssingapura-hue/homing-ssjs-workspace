package hue.captains.singapura.js.homing.workspace.bench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.workspace.groups.WorkspaceGroupsJs;

import java.util.List;

/**
 * The bench's groups, as its page provides them to the directory:
 * {@code BENCH_GROUPS}, generated from {@link BenchGroups#GROUPS}.
 */
public record BenchGroupsModule() implements EsModule<BenchGroupsModule>, SelfContent {

    public static final BenchGroupsModule INSTANCE = new BenchGroupsModule();

    public record BENCH_GROUPS() implements Exportable._Constant<BenchGroupsModule> {}

    @Override public ImportsFor<BenchGroupsModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<BenchGroupsModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new BENCH_GROUPS())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by BenchGroupsModule from BenchGroups.GROUPS - do not hand-edit.",
                WorkspaceGroupsJs.constant("BENCH_GROUPS", BenchGroups.GROUPS));
    }
}

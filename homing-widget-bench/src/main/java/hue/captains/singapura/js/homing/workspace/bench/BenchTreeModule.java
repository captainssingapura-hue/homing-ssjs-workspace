package hue.captains.singapura.js.homing.workspace.bench;

import hue.captains.singapura.js.homing.core.EsModule;
import hue.captains.singapura.js.homing.core.Exportable;
import hue.captains.singapura.js.homing.core.ExportsOf;
import hue.captains.singapura.js.homing.core.ImportsFor;
import hue.captains.singapura.js.homing.core.ModuleNameResolver;
import hue.captains.singapura.js.homing.core.SelfContent;
import hue.captains.singapura.js.homing.workspace.tree.TreeArrangementJs;

import java.util.List;

/**
 * The tree bench's arrangement, as its page lays it out: {@code BENCH_TREE}, generated from
 * {@link BenchTree#ARRANGEMENT}.
 */
public record BenchTreeModule() implements EsModule<BenchTreeModule>, SelfContent {

    public static final BenchTreeModule INSTANCE = new BenchTreeModule();

    public record BENCH_TREE() implements Exportable._Constant<BenchTreeModule> {}

    @Override public ImportsFor<BenchTreeModule> imports() { return ImportsFor.noImports(); }

    @Override
    public ExportsOf<BenchTreeModule> exports() { return new ExportsOf<>(INSTANCE, List.of(new BENCH_TREE())); }

    @Override
    public List<String> selfContent(ModuleNameResolver resolver) {
        return List.of("// Generated by BenchTreeModule from BenchTree.ARRANGEMENT - do not hand-edit.",
                TreeArrangementJs.constant("BENCH_TREE", BenchTree.ARRANGEMENT));
    }
}
